## 扫箱码的算法

扫到箱码（非单品码）时：`本次扣减 = min(本行剩余需求, 箱数 × 每箱件数)`。扫 2 箱（箱规 24）= 扣 48 件，台账 `qty=-48`。

这与收货侧折箱是**同一套函数**，不会出现"收货算 24、发料算 20"的口径漂移。

扫到未登记的码：不硬拦，按剩余量发，并给出 `packWarning` 提醒。

## 缺料怎么办

- 整行无库存 → 行标 `SHORT`，不落发料记录（避免"假的已发"）。
- 部分库存 → 标 `PARTIAL`，按实际数量发。
- 被跳过（如 `udi_required` 行没扫码）的行会在返回的 `skipped` 里列出原因。

## 退料

1. 只有 `ISSUED` 的工单能退料。
2. 必须填原因（如"产线余料退回"）。
3. 退料后库存回补、写 `RETURN` 追溯事件、工单回到 `ISSUING`。
